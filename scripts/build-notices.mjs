// Generates NOTICES.md from the license files installed in node_modules, so the bundled notice text is the real upstream text.
//   node scripts/build-notices.mjs           write NOTICES.md
//   node scripts/build-notices.mjs --check   fail if NOTICES.md is missing or differs from what node_modules implies
import { readFileSync, writeFileSync, existsSync } from "node:fs";
import { fileURLToPath } from "node:url";

const root = new URL("../", import.meta.url);
// Packages whose code is compiled into a shipped artifact.
//   main.js (Obsidian plugin): three (incl. examples/jsm loaders and post-processing), three-mesh-bvh
//   palace-memory.cjs (MCP server + CLI): @modelcontextprotocol/server, @modelcontextprotocol/core, zod
export const BUNDLED = [
  { name: "three", into: "plugin (main.js)", url: "https://github.com/mrdoob/three.js" },
  { name: "three-mesh-bvh", into: "plugin (main.js)", url: "https://github.com/gkjohnson/three-mesh-bvh" },
  { name: "@modelcontextprotocol/server", into: "memory server (palace-memory.cjs)", url: "https://github.com/modelcontextprotocol/typescript-sdk" },
  { name: "@modelcontextprotocol/core", into: "memory server (palace-memory.cjs)", url: "https://github.com/modelcontextprotocol/typescript-sdk" },
  { name: "zod", into: "memory server (palace-memory.cjs)", url: "https://github.com/colinhacks/zod" },
];

export function render() {
  const out = [];
  out.push(`# Third-party notices

Palace Atlas itself is MIT-licensed (see \`LICENSE\`). The release artifacts compile in the third-party packages below.
Their license texts follow verbatim, copied from the installed packages at build time (\`npm run notices\`).

## What is original

Every file in \`assets/\` is original work under this repository's MIT license; \`assets/LICENSES.md\` is the provenance statement
shipped next to them.

- The brain surfaces (\`assets/brain.glb\`, \`assets/brain_low.glb\`) are generated by \`scripts/build-brain.mjs\` and
  \`scripts/lib/cerebellum-geometry.mjs\` from closed-form shapes and seeded noise. The signed-distance field
  (\`assets/brain_sdf.bin\`) is derived from those meshes by \`scripts/build-sdf.ts\`.
- \`assets/morphologies.json\` holds 24 neuron morphologies grown by a seeded stochastic branching program
  (\`scripts/build-morphologies.mjs\`). Per-note neurons are grown by \`src/morph.ts\` (a greedy minimum-spanning-tree model after
  Cuntz et al. 2010, re-implemented here). They are not reconstructions of real cells.
- No scans, atlas meshes, or third-party neuron reconstructions (e.g. SWC archives) are bundled.
- The illustration is procedural and not anatomical. It does not depict any person's brain.
- The demo vault is synthetic.

## Bundled third-party code
`);
  for (const p of BUNDLED) {
    const dir = new URL(`node_modules/${p.name}/`, root);
    const pkg = JSON.parse(readFileSync(new URL("package.json", dir), "utf8"));
    const lic = readFileSync(new URL("LICENSE", dir), "utf8").replace(/\r\n/g, "\n").trimEnd();
    out.push(`### ${p.name} ${pkg.version}\n\n- License: ${pkg.license}\n- Source: ${p.url}\n- Compiled into: ${p.into}\n\n\`\`\`text\n${lic}\n\`\`\`\n`);
  }
  out.push(`## Not bundled

Build and test tooling (esbuild, TypeScript, Playwright, the \`obsidian\` type package, \`@modelcontextprotocol/client\`) is a
development dependency and is not part of any release artifact. Obsidian itself provides its API at runtime.
`);
  return out.join("\n");
}

// Re-bundle both shipped artifacts (in memory, nothing written) and list every node_modules package that ends up inside them.
export async function bundledPackages() {
  const { build } = await import("esbuild"), found = new Set();
  const jobs = [
    { entryPoints: ["src/main.ts"], platform: "browser", external: ["obsidian", "electron", "@codemirror/*", "@lezer/*"] },
    { entryPoints: ["memory/src/cli.ts"], platform: "node" },
  ].filter((j) => existsSync(new URL(j.entryPoints[0], root)));
  for (const j of jobs) {
    const r = await build({ ...j, bundle: true, write: false, metafile: true, format: "cjs", logLevel: "silent", absWorkingDir: fileURLToPath(root) });
    for (const f of Object.keys(r.metafile.inputs)) { const m = f.match(/(?:^|\/)node_modules\/((?:@[^/]+\/)?[^/]+)\//); if (m) found.add(m[1]); }
  }
  return [...found].sort();
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const target = new URL("NOTICES.md", root), text = render();
  if (process.argv.includes("--check")) {
    if (!existsSync(target) || readFileSync(target, "utf8") !== text) { console.error("NOTICES.md is stale: run `npm run notices`"); process.exit(1); }
    const listed = new Set(BUNDLED.map((p) => p.name)), actual = await bundledPackages(), unlisted = actual.filter((n) => !listed.has(n));
    if (unlisted.length) { console.error(`bundled but missing from NOTICES (add to BUNDLED): ${unlisted.join(", ")}`); process.exit(1); }
    console.log(`bundle audit: ${actual.join(", ")}`);
    console.log(`NOTICES.md up to date (${BUNDLED.length} bundled packages)`);
  } else { writeFileSync(target, text); console.log(`wrote NOTICES.md (${BUNDLED.length} bundled packages)`); }
}
